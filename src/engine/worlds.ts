export function chooseScenario(background: BackgroundId): Scenario {
  const choices = storyWorlds[background].scenarios
  const picked = choices[Math.floor(Math.random() * choices.length)]
  const places = openingPlaces[background]
  return {
    ...picked,
    place: places[Math.floor(Math.random() * places.length)],
    shape: openingShapes[Math.floor(Math.random() * openingShapes.length)],
    ...(() => {
      const draw = <T>(pool: T[]) =>
        pool[Math.floor(Math.random() * pool.length)]
      const playerRole = draw(playerRoles[background])
      // The two pools overlap in a few worlds (both sides can run a restaurant
      // overseas), and drawing the same job for both reads as a mistake.
      const men = maleRoles[background].filter((role) => role !== playerRole)
      return { playerRole, maleBackground: draw(men) }
    })(),
  }
}
