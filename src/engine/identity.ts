/** Names the story can give him, so the reader can reroll one before starting. */
export function maleNameOptions(background: BackgroundId, playerName = '') {
  const { surnames, names } = namePools(background)
  return surnames
    .flatMap((s) => names.map((n) => s + n))
    .filter((n) => n !== playerName.trim())
}

export const randomMaleName = (background: BackgroundId, playerName = '') => {
  const all = maleNameOptions(background, playerName)
  return all[Math.floor(Math.random() * all.length)]
}

export function generateIdentity(
  background: BackgroundId,
  trope: TropeId,
  playerName: string,
  /** Chosen by the reader; a blank one lets the story pick. */
  chosenName = '',
) {
  const { surnames, names } = namePools(background)
  return buildIdentity(
    background,
    trope,
    playerName,
    chosenName,
    surnames,
    names,
  )
}

function namePools(background: BackgroundId) {
  const surnames = [
    '沈',
    '陆',
    '许',
    '江',
    '周',
    '程',
    '顾',
    '裴',
    '季',
    '贺',
    '谢',
    '梁',
  ]
  const names =
    background === 'historical_court' || background === 'fantasy'
      ? ['怀川', '行简', '知衡', '闻舟', '照野', '庭安', '明珩', '云峥']
      : [
          '远舟',
          '叙宁',
          '景川',
          '时安',
          '清和',
          '予衡',
          '砚初',
          '闻序',
          '承峤',
          '望舒',
        ]
  return { surnames, names }
}

function buildIdentity(
  background: BackgroundId,
  trope: TropeId,
  playerName: string,
  chosenName: string,
  surnames: string[],
  names: string[],
) {
  const candidates = surnames
    .flatMap((s) => names.map((n) => s + n))
    .filter((n) => n !== playerName.trim())
  const setting = chooseScenario(background)
  return {
    maleName: chosenName.trim() || pick(candidates),
    playerBackground: `${setting.playerRole}。${pick(relationshipSeeds[trope])}`,
    // A direction, not the identity. The model writes the concrete one on the
    // first turn and it is pinned from then on, so two stories in the same
    // world do not open with the same man.
    maleHint: setting.maleBackground,
    openingClue: setting.clue,
    openingSituation: {
      place: setting.place,
      event: setting.event,
      socialCue: setting.socialCue,
      localLine: setting.localLine,
      maleHint: setting.maleBackground,
      shape: setting.shape,
    },
  }
}
