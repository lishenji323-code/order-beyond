import {chromium} from '@playwright/test'
import assert from 'node:assert/strict'
const browser=await chromium.launch({channel:'chrome',headless:true})
const context=await browser.newContext({viewport:{width:390,height:844}}),page=await context.newPage()
await page.goto('http://localhost:4173')
await page.evaluate(()=>navigator.serviceWorker.ready)
await page.getByRole('button',{name:'与我一起堕入梦境吧，公主'}).click()
for(let i=0;i<3;i++)await page.getByRole('button',{name:'下一步'}).first().click()
await page.getByLabel('你的名字').fill('小雨')
await page.getByRole('button',{name:'我的恋人，请与我相爱'}).click()
await page.locator('.story-message').waitFor()
await page.getByRole('textbox',{name:'回复他，或者做你想做的事'}).fill('还没有发送的话。')
await page.evaluate(()=>document.fonts.ready)
await page.reload();await page.locator('.story-message').waitFor()
const original=await page.locator('.story-message').innerText()
assert.equal(await page.locator('textarea').inputValue(),'还没有发送的话。')
await context.setOffline(true);await page.reload();await page.locator('.story-message').waitFor()
assert.equal(await page.locator('.story-message').innerText(),original)
assert.equal(await page.locator('textarea').inputValue(),'还没有发送的话。')
await page.screenshot({path:'test-results/product-offline.png'})
console.log('PASS: production service worker, offline reload, saved story and unsent draft restored')
await browser.close()
