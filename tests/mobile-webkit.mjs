import { webkit,devices } from '@playwright/test'
import assert from 'node:assert/strict'
const browser=await webkit.launch({headless:true})
const page=await browser.newPage({...devices['iPhone 13']})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.goto('http://localhost:5173')
await page.getByRole('button',{name:'与我一起堕入梦境吧，公主'}).click()
for(let i=0;i<3;i++)await page.getByRole('button',{name:'下一步'}).first().click()
await page.getByLabel('你的名字').fill('林夏');await page.getByRole('button',{name:'我的恋人，请与我相爱'}).click()
await page.locator('.story-message').waitFor()
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
const scrolled=await page.locator('.story-feed').evaluate(e=>{e.scrollTop=200;return e.scrollTop})
assert.ok(scrolled>0)
await page.getByRole('textbox',{name:'回复他，或者做你想做的事'}).fill('我想看那封信。')
await page.reload();await page.locator('.story-message').waitFor()
assert.equal(await page.locator('textarea').inputValue(),'我想看那封信。')
assert.deepEqual(errors,[])
await page.screenshot({path:'test-results/iphone-webkit.png'})
console.log('PASS: iPhone viewport / WebKit engine, creation, reading scroll, draft persistence, no overflow or runtime errors')
await browser.close()
